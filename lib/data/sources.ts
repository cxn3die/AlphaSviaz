export function getSource(slug: string) {
  return sources.find((source) => source.slug === slug);
}

/** Ссылка «источник» для карточки на главной */
export function getSourceHref(cardId: string) {
  const source = sources.find((item) => item.cardId === cardId);
  return source ? `/sources/${source.slug}` : "/sources";
}
